// Writes worker/nerds-trends.ts: the id, name, category and years of every
// trend, small enough to bundle into the Worker. The chart planner shows it to
// Claude so it can only pick trends that exist.
//
// Usage, from the repo root: node datasets/fashion/scripts/trend-index.mjs
// Deterministic for the same fashion.json.

import { readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync('public/nerds-of-fashion/fashion.json', 'utf8'));
const { from, to } = data.meta.years;

const rows = data.trends.map((t) => {
  const starts = t.periods.map((p) => Math.max(from, p.start));
  const ends = t.periods.map((p) => Math.min(to, p.end));
  return [t.id, t.name, t.category, Math.min(...starts), Math.max(...ends)];
});

writeFileSync(
  'worker/nerds-trends.ts',
  `// Generated by datasets/fashion/scripts/trend-index.mjs. Do not edit by hand.
export type TrendRow = [id: string, name: string, category: string, first: number, last: number];

export const TREND_YEARS = { from: ${from}, to: ${to} };

export const TRENDS: TrendRow[] = ${JSON.stringify(rows)};
`,
);
console.log(`${rows.length} trends`);
